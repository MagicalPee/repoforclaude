import type { LayoutSpec, MotionSpec, ShapeSpec, SpacingSpec } from "./foundations.js";
import type { PaletteSpec, ThemeColors } from "./palette.js";
import type { FontChoice, TypographySpec } from "./typography.js";

export interface TokenSource {
  id: string;
  concept: string;
  palette: PaletteSpec;
  typography: TypographySpec;
  spacing: SpacingSpec;
  layout: LayoutSpec;
  shape: ShapeSpec;
  motion: MotionSpec;
}

function stack(font: FontChoice): string {
  // Fontsource variable packages register "<Family> Variable"; list both so either loading method works.
  if (font.source === "google-fonts" && font.variable && font.fontsourcePackage?.includes("-variable")) {
    return `"${font.family} Variable", ${font.stack}`;
  }
  return font.stack;
}

function colorLines(theme: ThemeColors, indent = "  "): string[] {
  return Object.entries(theme).map(([k, v]) => `${indent}--color-${k}: ${v.hex};`);
}

function nonColorLines(t: TokenSource): string[] {
  const ty = t.typography;
  const lines: string[] = [];
  lines.push("  /* typography */");
  lines.push(`  --font-heading: ${stack(ty.heading)};`);
  lines.push(`  --font-body: ${stack(ty.body)};`);
  lines.push(`  --font-mono: ${stack(ty.mono)};`);
  for (const s of ty.scale.steps) lines.push(`  --text-${s.token}: ${s.fluid ?? s.rem};`);
  for (const [name, st] of Object.entries(ty.styles)) {
    lines.push(`  --text-${name}: ${st.size};`);
    lines.push(`  --leading-${name}: ${st.lineHeight};`);
    lines.push(`  --tracking-${name}: ${st.letterSpacing};`);
  }
  lines.push(`  --font-weight-regular: ${ty.weights.regular};`);
  lines.push(`  --font-weight-medium: ${ty.weights.medium};`);
  lines.push(`  --font-weight-semibold: ${ty.weights.semibold};`);
  lines.push(`  --font-weight-bold: ${ty.weights.bold};`);
  lines.push(`  --font-weight-heading: ${ty.weights.heading};`);
  lines.push("", "  /* spacing (4px base) */");
  for (const [k, v] of Object.entries(t.spacing.scale)) lines.push(`  --space-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.spacing.semantic)) lines.push(`  --space-${k}: ${v};`);
  lines.push("", "  /* layout */");
  lines.push(`  --container-max: ${t.layout.containerMaxWidth};`);
  lines.push(`  --container-reading: ${t.layout.readingWidth};`);
  lines.push(`  --container-wide: ${t.layout.wideWidth};`);
  lines.push(`  --page-padding: ${t.layout.pagePadding.mobile};`);
  lines.push(`  --grid-gutter: ${t.layout.grid.gutter.mobile};`);
  lines.push(`  --section-spacing: ${t.layout.sectionSpacing.fluid};`);
  lines.push("", "  /* shape */");
  for (const [k, v] of Object.entries(t.shape.radius)) lines.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.shape.componentRadius)) lines.push(`  --radius-${k}: ${v};`);
  lines.push(`  --border-hairline: ${t.shape.borderWidth.hairline};`);
  lines.push(`  --border-default: ${t.shape.borderWidth.default};`);
  lines.push(`  --border-strong: ${t.shape.borderWidth.strong};`);
  for (const [k, v] of Object.entries(t.shape.shadows)) lines.push(`  --shadow-${k}: ${v};`);
  lines.push("", "  /* motion */");
  for (const [k, v] of Object.entries(t.motion.durations)) lines.push(`  --duration-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.motion.easing)) lines.push(`  --ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.motion.transitions)) lines.push(`  --transition-${k}: ${v};`);
  return lines;
}

/** Framework-agnostic tokens + minimal base styles as one CSS file. */
export function toCss(t: TokenSource): string {
  const p = t.palette;
  const primary = p.defaultMode === "dark" ? p.dark : p.light;
  const secondary = p.defaultMode === "dark" ? p.light : p.dark;
  const otherMode = p.defaultMode === "dark" ? "light" : "dark";
  const out: string[] = [];
  out.push(`/* ${t.concept} — generated by design-intelligence-mcp (${t.id}). Edit values here, not in components. */`);
  out.push(":root {");
  out.push(`  color-scheme: ${p.modes.length > 1 ? `${p.defaultMode} ${otherMode}` : p.defaultMode};`);
  out.push(`  /* color (${p.defaultMode}) */`);
  if (primary) out.push(...colorLines(primary));
  out.push("");
  out.push(...nonColorLines(t));
  out.push("}");
  if (secondary) {
    out.push("");
    out.push(`[data-theme="${otherMode}"] {`);
    out.push(`  color-scheme: ${otherMode};`);
    out.push(...colorLines(secondary));
    out.push("}");
    out.push(`@media (prefers-color-scheme: ${otherMode}) {`);
    out.push(`  :root:not([data-theme="${p.defaultMode}"]) {`);
    out.push(`    color-scheme: ${otherMode};`);
    out.push(...colorLines(secondary, "    "));
    out.push("  }");
    out.push("}");
  }
  out.push("");
  out.push(`@media (min-width: ${t.layout.breakpoints.md}) { :root { --page-padding: ${t.layout.pagePadding.tablet}; --grid-gutter: ${t.layout.grid.gutter.tablet}; } }`);
  out.push(`@media (min-width: ${t.layout.breakpoints.lg}) { :root { --page-padding: ${t.layout.pagePadding.desktop}; --grid-gutter: ${t.layout.grid.gutter.desktop}; } }`);
  out.push("");
  out.push("/* base */");
  out.push("body { margin: 0; background: var(--color-background); color: var(--color-text); font-family: var(--font-body); font-size: var(--text-body); line-height: var(--leading-body); -webkit-font-smoothing: antialiased; text-rendering: optimizeLegibility; }");
  for (const h of ["h1", "h2", "h3", "h4", "h5", "h6"]) {
    const st = t.typography.styles[h]!;
    const family = st.fontFamily === "heading" ? "var(--font-heading)" : st.fontFamily === "mono" ? "var(--font-mono)" : "var(--font-body)";
    out.push(`${h} { font-family: ${family}; font-size: var(--text-${h}); line-height: var(--leading-${h}); letter-spacing: var(--tracking-${h}); font-weight: ${st.weight};${st.textTransform ? ` text-transform: ${st.textTransform};` : ""} text-wrap: balance; margin: 0; }`);
  }
  out.push("p { text-wrap: pretty; }");
  out.push("a { color: var(--color-link); text-decoration-thickness: from-font; text-underline-offset: 0.18em; }");
  out.push("a:hover { color: var(--color-link-hover); }");
  out.push(":focus-visible { outline: 2px solid var(--color-focus-ring); outline-offset: 2px; }");
  out.push("::selection { background: var(--color-primary-subtle); color: var(--color-text); }");
  out.push("code, kbd, samp, pre { font-family: var(--font-mono); font-size: 0.92em; }");
  out.push(".tabular-nums, table, [data-numeric] { font-variant-numeric: tabular-nums; }");
  out.push(t.motion.reducedMotion);
  return `${out.join("\n")}\n`;
}

/** Tailwind CSS v4: tokens as @theme variables so utilities like bg-primary and font-heading exist. */
export function toTailwindV4(t: TokenSource): string {
  const p = t.palette;
  const primary = (p.defaultMode === "dark" ? p.dark : p.light)!;
  const secondary = p.defaultMode === "dark" ? p.light : p.dark;
  const otherMode = p.defaultMode === "dark" ? "light" : "dark";
  const ty = t.typography;
  const out: string[] = [];
  out.push('@import "tailwindcss";');
  if (secondary) out.push(`@custom-variant ${otherMode} (&:where([data-theme=${otherMode}], [data-theme=${otherMode}] *));`);
  out.push("");
  out.push("@theme {");
  out.push(...colorLines(primary));
  out.push(`  --font-heading: ${stack(ty.heading)};`);
  out.push(`  --font-body: ${stack(ty.body)};`);
  out.push(`  --font-mono: ${stack(ty.mono)};`);
  for (const [name, st] of Object.entries(ty.styles)) {
    out.push(`  --text-${name}: ${st.size};`);
    out.push(`  --text-${name}--line-height: ${st.lineHeight};`);
    out.push(`  --text-${name}--letter-spacing: ${st.letterSpacing};`);
    out.push(`  --text-${name}--font-weight: ${st.weight};`);
  }
  out.push("  --spacing: 0.25rem;");
  for (const [k, v] of Object.entries(t.shape.radius)) if (k !== "none" && k !== "full") out.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.shape.componentRadius)) out.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.shape.shadows)) out.push(`  --shadow-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.motion.easing)) out.push(`  --ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.layout.breakpoints)) out.push(`  --breakpoint-${k}: ${v};`);
  out.push(`  --container-reading: ${t.layout.readingWidth};`);
  out.push(`  --container-site: ${t.layout.containerMaxWidth};`);
  out.push("}");
  if (secondary) {
    out.push("");
    out.push(`[data-theme="${otherMode}"] {`);
    out.push(...colorLines(secondary));
    out.push("}");
    out.push(`@media (prefers-color-scheme: ${otherMode}) {`);
    out.push(`  :root:not([data-theme="${p.defaultMode}"]) {`);
    out.push(...colorLines(secondary, "    "));
    out.push("  }");
    out.push("}");
  }
  out.push("");
  out.push("@layer base {");
  out.push("  body { @apply bg-background text-text font-body text-body; }");
  out.push("  h1 { @apply font-heading text-h1; } h2 { @apply font-heading text-h2; } h3 { @apply font-heading text-h3; } h4 { @apply font-heading text-h4; }");
  out.push("  a { @apply text-link underline underline-offset-4 hover:text-link-hover; }");
  out.push("  :focus-visible { outline: 2px solid var(--color-focus-ring); outline-offset: 2px; }");
  out.push("}");
  return `${out.join("\n")}\n`;
}

/** Tailwind CSS v3: theme.extend that points at the CSS variables from tokens.css. */
export function toTailwindV3(t: TokenSource): string {
  const theme = (t.palette.light ?? t.palette.dark)!;
  const colors = Object.keys(theme)
    .map((k) => `        "${k}": "var(--color-${k})",`)
    .join("\n");
  const fontSize = Object.entries(t.typography.styles)
    .map(([k, s]) => `        "${k}": ["var(--text-${k})", { lineHeight: "${s.lineHeight}", letterSpacing: "${s.letterSpacing}", fontWeight: "${s.weight}" }],`)
    .join("\n");
  const radius = Object.keys({ ...t.shape.radius, ...t.shape.componentRadius })
    .map((k) => `        "${k}": "var(--radius-${k})",`)
    .join("\n");
  const shadows = Object.keys(t.shape.shadows)
    .map((k) => `        "${k}": "var(--shadow-${k})",`)
    .join("\n");
  return `// tailwind.config.js (v3): import tokens.css in your global stylesheet first.
/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: ["selector", '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: {
${colors}
      },
      fontFamily: {
        heading: ["var(--font-heading)"],
        body: ["var(--font-body)"],
        mono: ["var(--font-mono)"],
      },
      fontSize: {
${fontSize}
      },
      borderRadius: {
${radius}
      },
      boxShadow: {
${shadows}
      },
      maxWidth: { reading: "var(--container-reading)", site: "var(--container-max)" },
      transitionTimingFunction: { standard: "var(--ease-standard)", emphasized: "var(--ease-emphasized)" },
    },
  },
};
`;
}

/** W3C Design Tokens Community Group format (composite values kept as CSS strings). */
export function toDtcg(t: TokenSource): Record<string, unknown> {
  const color = (theme: ThemeColors | undefined) =>
    theme ? Object.fromEntries(Object.entries(theme).map(([k, v]) => [k, { $type: "color", $value: v.hex, $description: v.usage }])) : undefined;
  const ty = t.typography;
  return {
    $description: `${t.concept} (${t.id}) — generated by design-intelligence-mcp`,
    color: { light: color(t.palette.light), dark: color(t.palette.dark) },
    font: {
      family: {
        heading: { $type: "fontFamily", $value: ty.heading.stack.split(/,\s*/).map((f) => f.replace(/"/g, "")) },
        body: { $type: "fontFamily", $value: ty.body.stack.split(/,\s*/).map((f) => f.replace(/"/g, "")) },
        mono: { $type: "fontFamily", $value: ty.mono.stack.split(/,\s*/).map((f) => f.replace(/"/g, "")) },
      },
      weight: Object.fromEntries(Object.entries(ty.weights).map(([k, v]) => [k, { $type: "fontWeight", $value: v }])),
      size: Object.fromEntries(ty.scale.steps.map((s) => [s.token, { $type: "dimension", $value: `${s.px}px`, $extensions: s.fluid ? { css: s.fluid } : undefined }])),
    },
    typography: Object.fromEntries(
      Object.entries(ty.styles).map(([k, s]) => [
        k,
        { $type: "typography", $value: { fontFamily: `{font.family.${s.fontFamily}}`, fontSize: s.size, fontWeight: s.weight, lineHeight: s.lineHeight, letterSpacing: s.letterSpacing } },
      ]),
    ),
    space: Object.fromEntries(Object.entries(t.spacing.scale).map(([k, v]) => [k, { $type: "dimension", $value: v }])),
    radius: Object.fromEntries(Object.entries({ ...t.shape.radius, ...t.shape.componentRadius }).map(([k, v]) => [k, { $type: "dimension", $value: v }])),
    shadow: Object.fromEntries(Object.entries(t.shape.shadows).map(([k, v]) => [k, { $value: v, $description: "CSS box-shadow string" }])),
    duration: Object.fromEntries(Object.entries(t.motion.durations).map(([k, v]) => [k, { $type: "duration", $value: v }])),
    easing: Object.fromEntries(Object.entries(t.motion.easing).map(([k, v]) => [k, { $type: "cubicBezier", $value: v }])),
    breakpoint: Object.fromEntries(Object.entries(t.layout.breakpoints).map(([k, v]) => [k, { $type: "dimension", $value: v }])),
  };
}
